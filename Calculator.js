const calculator = {
    add: function(a, b) {
        return a + b;
    },
    sub: function(a, b) {
        return a - b;
    },
    multiply: function(a, b) {
        return a * b;
    },
    divide: function(a, b) {
        return a / b;
    }
};
console.log(calculator.add(10, 5));
console.log(calculator.sub(10, 5));
console.log(calculator.multiply(10, 5));
console.log(calculator.divide(10, 5));